//   · kanji  日语稿面写法，只作注释与验收比对（whisper 转写的字错率对它算），不进任何提示词。
//   · 屏幕字幕是 Notion 稿里的中文，写在台词表的 line.text 上。
// 键：逐句 id「<Scene>.<NN>」。
//
// 2026-10-11 Notion 稿只给中文（「日军对白以日语播放，下文列游戏中文译文」），日语写法由 Voice 包定：
//   · 日兵甲是冷静的老兵分队长，话短，用「こいつ」指人，不骂人；全段唯一的蔑称是割喉时嘟囔的「支那豚」。
//   · 「丁。过来。」不把「丁」当名字念，叫的是「おい、しんぺい」（喂，新兵）。
//   · 「支那猪，叫得倒响。」是低声嘟囔，照意译：しなぶたが、よくなきやがる（支那豚が、よく鳴きやがる）。
