// 户口册里 collapsed / burnt 的密度这里最高。所以这一片的基调不是「过日子」
// 而是「被战火碾过的家」：掀散的石块、砸烂翻倒的箱子、烧剩的枯树、
// 来不及带走的粮食、丢在院里的逃难车。
//
// 三条布位口径（照 Script_CityBlockKit 的六种原型反推，再用 --phase=4 出图核过）：
//   · 正房永远在院子北边（局部 dz ≈ -d/2 .. -d/2+6），厢房贴东西院墙、
//     影壁在门内 2 m —— 件一律摆在这三样之间的那块空地上；
//   · 土墙院（AdobeYard）南三分之一有一道 1.1 m 的隔墙（局部 dz = d*0.16），
//     件摆在隔墙以南；水井院（WellYard）的井台占掉南院心 dx±2.7，件靠边摆；
//   · Script_LivedInProps 的缸/篮/柴垛在「靠院墙、偏后」一带，
//     这里的件一律往院心南半边错开，是补充不是叠加。
//
// 玩家动线：四·城墙关的目标链（276,-65)→(288,-65)→(294,288)→(150,296)→(285,296)
// 贴着东墙与南墙走，所以东墙内侧那一列（x≈272）与南墙内侧那一行（z≈275）
// 的院子是真会被看见的，件优先给了它们；十字街东南的三户是对照组
// （五·十字街关的 detail 档），故意留了两户还齐整的人家。
//
// ---------------------------------------------------------------------------
// 【2026-08-25 加密轮：34 件/16 户 → 133 件/52 户】
//
// 视觉走了流送（见 Script_PropStreaming 文件头）之后，件数的预算不再是全城
// draw call，而是「焦点附近同时活着多少」。这一轮补的是**密度**与**读法**：
//
//   · 一户一组有逻辑的家什，不是撒点。上一轮这一片只有石头、砖瓦、木箱、
//     枯树、米袋 —— 全是「被砸过」的名词，读起来像战场不像街坊。这一轮每一户
//     都先答一个问题：**碾过之前，这院子里的人在过什么日子？** 于是有了
//     推磨的磨盘与磨边的凳、挑水的桶与洗衣的盆、劈柴的墩子与码齐的柴垛、
//     腌菜的坛与晾衣的架。砸碎的水缸旁边一定立着一只没事的咸菜坛，
//     烧塌的院里磨盘一定还在原位 —— 「碾过」是要有对照物才读得出来的。
//   · 「翻倒」只能用**散乱的间距与朝向**表达：摆位系统没有翻倒姿态，
//     凳子只能立着。所以同一组里的两件永远不同朝向、不成一条线；
//     完好户（blk11_24、blk19_15）反过来，一律摆正、朝向一致。
//   · 局部密度守两条闸：单院 ≤ 8 件（本片最多 4 件），45 m 邻域 ≤ 90 件
//     （本片最密的东墙一列实测 30 上下）。碰撞不流送 —— 巷口与院门一件不放。
//   · 中/远景档的合并体块比近景正房大**一圈**，只按近景推空位必埋墙。
//     这一轮的每个落点都先对过 L4/L5/L6 三关的真实碰撞盒（引擎导出的那张表），
//     再交给 Script_DressingProbeTest 复核。
//
