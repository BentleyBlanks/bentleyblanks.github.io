const L = (keyframe, who, speaker, lang, text, direction, projection = "normal", extra = {}) =>
  ({ keyframe, who, speaker, lang, text, subtitle: text, direction, projection, ...extra });
const JA = (keyframe, who, speaker, kana, kanji, subtitle, direction, projection = "normal", extra = {}) =>
  ({ keyframe, who, speaker, lang: "ja", text: kana, subtitle, direction, projection, kanji, ...extra });

function Scene(id, beat, label, context, lines, extra = {}) {
  const numbered = lines.map((line, i) => Object.freeze({ id: `${id}.${String(i + 1).padStart(2, "0")}`, ...line }));
  return Object.freeze({
    id, beat, keyframe: numbered[0].keyframe, keyframes: Object.freeze([...new Set(numbered.map((l) => l.keyframe))]), label, context,
    cast: Object.freeze([...new Set(lines.map((l) => l.who))]), ...extra, lines: Object.freeze(numbered),
  });
}

