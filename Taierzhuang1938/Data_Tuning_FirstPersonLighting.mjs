// 第一人称手与枪的取光（2026-11-02，用户：背向太阳时枪这么黑）。
//
// 病根：汉阳造 173R 的钢件是纯金属（ORM 金属度 ≈ 1），没有漫反射，只能映出别处的光。
// 背光时镜面方向对着前方的地面与沟壁，天空 IBL ×0.34 的下半球又只是一块暗地色，
// 于是整块发黑；视模还按自己被压缩过的位置去采世界阴影图，玩家影子替身与沟壁的影子
// 会一块块落到枪上。
//
// 改法照 COD 公开的做法（出处见 docs/Data_TechRenderPipeline.md「第一人称取光」一节）：
//   sun        太阳照不照得到在**眼睛**那几个点上算（COD4 的 lightingOrigin、IW 的屏幕空间阴影），
//              不再逐像素采世界阴影图；手—枪之间的遮挡仍归第一人称自阴影那张小图。
//   reflection 跟着玩家走的本地反射图（IW 起的反射探针 + 黑色行动 2 的「反射跟着当地亮度走」）：
//              在眼睛处拍一张低分辨率立方体图、预滤波后只给视模材质当 envMap。
// 两项都只作用在第一人称自阴影那份视模材质上（Script_FirstPersonSelfShadow 的克隆），
// 世界材质一个字不动。画质面板可分别关掉，关掉就是改之前的样子（参考版）。
export const FIRST_PERSON_LIGHTING = Object.freeze({
  sun: Object.freeze({
    // 取样点：相机局部坐标（米，-Z 朝前、+Y 朝上、+X 朝右），按**真实尺寸**的握枪位置，
    // 不是视模压缩后的位置。眼睛一个、枪身中段一个、枪口一带一个，平均成 0…1。
    samples: Object.freeze([
      Object.freeze([0, 0, 0]),
      Object.freeze([0.10, -0.16, -0.35]),
      Object.freeze([0.06, -0.10, -0.80]),
    ]),
    // 朝太阳方向的射线最远查多远（米）。比这远的遮挡（远处的楼）不算，避免整条街跟着一栋远楼变暗。
    maxDistance: 160,
    // 平滑时间常数（秒）：进出屋檐的一刹那不跳变，三点平均的 1/3 台阶也被抹平。
    smoothS: 0.12,
  }),
  reflection: Object.freeze({
    // 立方体每面边长。**必须与天空 IBL 的 PMREM 一样大**（Script_Sky 的 fromScene 默认 256）：
    // 尺寸写进着色器的 CUBEUV 常量，不一样就要给视模材质另编一份程序，换上的那一帧卡一下。
    size: 256,
    near: 0.15,
    // 只拍身边这一圈；远处与天空用天空 IBL 补（背景就是那张图，亮度按当前环境反射强度）。
    // 一面的开销基本跟这一圈里的 draw call 走：2026-11-02 白盒 02 沟里无头实测一面 ≈ 3.9 ms（60 m 时）。
    far: 40,
    // 离上一次拍摄点走开多远就重拍（米），或者隔多久必重拍（秒，跟上天光 / 爆炸 / 开关灯）。
    // 站着不动只按 maxAgeS 重拍，平均开销 ≈ 一面的耗时 × 6 ÷ (maxAgeS × 帧率)。
    moveM: 4,
    maxAgeS: 4,
    // 拍的时候每隔几帧拍一面、一次拍几面。2 / 1 = 十二帧拍完一张，单帧尖峰最小；
    // 拍完六面才整张换上，不会半新半旧。
    faceEveryFrames: 2,
    facesPerFrame: 1,
    // 本地反射图里存的是真实辐亮度（世界材质的出画结果），按物理就是 1。
    intensity: 1,
  }),
});
