//
// 三层内容，三种活法：
//   · 东门大街延长段（z=-65 两侧）—— 关厢铺户与农户混居：柜台家什、米袋木箱、
//     门板招牌，以及濠外空地上撂下的、往城里逃时挑不动的那几件；
//   · 院落迷宫（寺院地与关厢院落群）—— 巷战前夜的生活：缸瓮桌凳笸箩水桶柴垛，
//     一律落在院里的空地与院墙根，不堵门道、不进两米巷；
//   · 农田带（东缘，BuildEastApproach 的田/坟/独户农院）—— 农活：草垛、石槽、
//     井台、锄锹斧、劈柴墩、晾晒架、大车轮、木料堆。
//
// 战损梯度照 BuildEastSuburb 的 rawDamage 走：**越靠城濠、越靠主路越烂**
//（那是日军突破方向与炮火校正的基准线），越往东南越完整 —— 西头的院子里是
// 掀翻的箱子与滚落的墙石，东南头的院子里桌凳还是端正的。
//
// 【选点纪律】城外没有户口册，所以三条自己立的规矩：
//   · 位置一律取自引擎碰撞真值（L2/L3/L4 三关各建一次，取三关净空的**最小值**）——
//     中/远景合并体块比近景正房大一圈，只按一关找的空位会在另一关埋进墙里；
//   · 不进护城河（东门外因瓮城外凸，濠在 x 335–345）、不进地隙（x 548–562 的冲沟）、
//     不进两条第一区公所/第731团1营的预留地（那两处院落归 Script_Landmark_EastSuburb）；
//   · 主路净空带（|z+65| < 4.2 m）一件实心的都不放 —— 那条土路是 L3 反攻的进攻轴线。

