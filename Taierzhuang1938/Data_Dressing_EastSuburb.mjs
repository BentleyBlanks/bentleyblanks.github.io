//
// 【这一片摆的是什么】
// 东关是关厢，不是城。日方战后检讨说得明白：「对守军有利的不是城墙的高度与坚固，
// 而是外城的存在与环绕城墙的密集民房的存在。」这里的每一件都要为那句话作证 ——
// 三月十六日下午到十七日下午，这片院子一间一间被爆破打通，而院里的日子是**前一天
