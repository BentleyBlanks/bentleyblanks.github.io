import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { LaunchBrowser } from "../PrairieFire1937/Script_BrowserTestKit.mjs";
import { ServeRoot } from "./Script_DevServer.mjs";
import { HISTORY_CODEX_ENTRIES, HISTORY_CODEX_CATEGORIES } from "./Data_HistoryCodex.mjs";

const root=path.resolve(import.meta.dirname,".."),out=path.join(import.meta.dirname,"_shots/HistoryCodex");
await fs.mkdir(out,{recursive:true});
const supplied=process.argv.find(arg=>arg.startsWith("--url="))?.slice(6);
const server=supplied?null:await ServeRoot(root,0),origin=supplied||`http://127.0.0.1:${server.address().port}`;
let browser;
try {
  browser=await LaunchBrowser();
  const page=await browser.newPage({viewport:{width:1920,height:1080}}),errors=[],failed=[],images=[];
  page.on("pageerror",error=>errors.push(String(error)));
  page.on("response",response=>{if(response.status()>=400)failed.push(`${response.status()} ${response.url()}`);});
  page.on("request",request=>{if(request.url().includes("/Menu/History/"))images.push(request.url());});
  await page.goto(`${origin}/Taierzhuang1938/?quality=high`,{waitUntil:"commit"});
  await page.waitForFunction(()=>window.Tengxian?.state.ready&&window.Tengxian.menu.open,null,{timeout:120000});
  assert.equal(images.length,0,"Title screen must not load archive assets");
  await page.click('[data-act="codex"]');
  await page.locator(".hcCard").first().waitFor();
  await page.evaluate(()=>document.fonts.ready);
  const Loaded=()=>page.waitForFunction(()=>[...document.querySelectorAll(".hcRoot img")].every(image=>image.complete&&image.naturalWidth>0));
  const Shot=async name=>{await Loaded();const buffer=await page.screenshot({path:path.join(out,`Scene_${name}.png`)});await sharp(buffer).resize({width:1280,height:720,fit:"inside",withoutEnlargement:true}).jpeg({quality:82}).toFile(path.join(out,`Preview_${name}.jpg`));};
  const State=()=>page.evaluate(()=>{const c=window.Tengxian.menu.historyCodex;return{mode:window.Tengxian.menu.mode,filter:c.filter,entry:c.entryId,page:c.page,scale:c.reader?.scale,x:c.reader?.x,y:c.reader?.y};});
  assert.equal(await page.locator(".hcCard").count(),5);await Shot("Overview");
  for(const category of HISTORY_CODEX_CATEGORIES){
    await page.click(`[data-hc-action="category"][data-hc-id="${category}"]`);
    assert.equal(await page.locator(".hcCard").count(),1,`Filter ${category}`);
    await page.locator(".hcCard").click();
    assert.equal((await State()).entry,HISTORY_CODEX_ENTRIES.find(entry=>entry.category===category).id);
    await Shot(category);
    if(category==="people")assert.ok(await page.locator(".hcRelated").evaluate(el=>el.getBoundingClientRect().bottom<=el.parentElement.getBoundingClientRect().bottom+1),"Related reading fits in the desktop biography");
    await page.keyboard.press("Escape");
    assert.equal((await State()).entry,null,"First Escape returns to the filtered list");
    assert.equal((await State()).filter,category);
  }
  await page.click('[data-hc-action="category"][data-hc-id="all"]');
  await page.locator(".hcCard").first().focus();await page.keyboard.press("ArrowDown");await page.keyboard.press("Enter");
  assert.equal((await State()).entry,"TengxianBattle","Keyboard opens the selected record");
  await page.click('[data-hc-action="stage"][data-hc-index="4"]');
  assert.match(await page.locator(".hcStage").innerText(),/滕县失守/);await page.keyboard.press("Escape");
  await page.click('[data-hc-action="open"][data-hc-id="WangMingzhang"]');await page.keyboard.press("r");
  assert.equal(await page.locator("dialog").evaluate(dialog=>dialog.open),true);
  assert.ok(await page.locator("dialog a").count()>=2);
  assert.equal(await page.locator("dialog a").first().getAttribute("rel"),"noopener noreferrer");
  await page.keyboard.press("Escape");assert.equal((await State()).entry,"WangMingzhang","Escape closes only sources");
  await page.click('[data-hc-action="related"][data-hc-id="ZhangMemoir"]');await Loaded();
  assert.equal((await State()).page,0);assert.ok(await page.locator('[data-hc-action="previous"]').isDisabled());
  assert.ok(!images.some(url=>/ZhangMemoir17Image/.test(url)),"Unopened pages remain unloaded");
  for(let i=1;i<17;i++){await page.click('[data-hc-action="next"]');await Loaded();assert.equal((await State()).page,i);}
  assert.ok(await page.locator('[data-hc-action="next"]').isDisabled());assert.match(await page.locator(".hcReaderHint").innerText(),/77/);
  await page.keyboard.press("PageUp");await Loaded();assert.equal((await State()).page,15);
  for(let i=0;i<5;i++)await page.click('[data-hc-action="zoomIn"]');assert.equal((await State()).scale,2.25);
  const box=await page.locator(".hcViewport").boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();
  await page.mouse.move(box.x+box.width/2+80,box.y+box.height/2+65,{steps:5});await page.mouse.up();
  assert.ok(Math.abs((await State()).x)+Math.abs((await State()).y)>0,"Zoomed image pans");
  await page.click('[data-hc-action="fit"]');assert.equal((await State()).scale,1);assert.equal((await State()).x,0);assert.equal((await State()).y,0);
  await page.click('[data-hc-action="expand"]');assert.equal(await page.locator(".hcReader.expanded").count(),1);
  await page.keyboard.press("Escape");assert.equal((await State()).entry,"ZhangMemoir","Escape leaves enlargement first");
  await page.click('[data-hc-action="readTab"][data-hc-id="sourceInfo"]');assert.equal(await page.locator(".hcSourceInfo a").count(),1);
  await page.keyboard.press("Escape");await page.click('[data-hc-action="restoration"]');
  assert.ok(await page.locator(".mnCodexRow").count()>20,"Restoration disclosures retained");
  await page.keyboard.press("Escape");assert.equal(await page.locator(".hcCard").count(),5);
  await page.setViewportSize({width:390,height:844});await Shot("MobileOverview");
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),"No mobile document overflow");
  await page.click('[data-hc-action="open"][data-hc-id="XinhuaDaily"]');await Shot("MobilePress");
  const back=await page.locator('[data-hc-action="back"]').first().boundingBox();assert.ok(back.x>=0&&back.x+back.width<=390);
  await page.keyboard.press("Escape");await page.keyboard.press("Escape");assert.equal((await State()).mode,"title");
  await page.evaluate(()=>{const m=window.Tengxian.menu;m.live=false;m.Show("pause");m.Activate("codex");});
  await page.keyboard.press("Escape");assert.equal((await State()).mode,"pause","Return to pause when opened there");
  assert.deepEqual(errors,[]);assert.deepEqual(failed,[]);
  await fs.writeFile(path.join(out,"Data_BrowserResult.json"),JSON.stringify({passed:true,images:[...new Set(images)],errors,failed},null,2));
  console.log("PASS HistoryCodex: filters/details, keyboard/back stack, sources, related records, 17 pages, zoom/pan/enlargement, restoration, mobile and lazy loading");
} finally {await browser?.close();if(server)await new Promise(resolve=>server.close(resolve));}
