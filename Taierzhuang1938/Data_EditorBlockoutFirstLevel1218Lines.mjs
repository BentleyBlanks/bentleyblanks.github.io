const L = (who, speaker, lang, text, subtitle, direction, projection = "normal", extra = {}) =>
  Object.freeze({ who, speaker, lang, text, subtitle, direction, projection, ...extra });

function Scene(id, beat, keyframe, label, context, lines) {
  const numbered = lines.map((line, i) => Object.freeze({ id: `${id}.${String(i + 1).padStart(2, "0")}`, keyframe, ...line }));
  return Object.freeze({ id, beat, keyframe, label, context, cast: Object.freeze([...new Set(lines.map((l) => l.who))]), lines: Object.freeze(numbered) });
}

