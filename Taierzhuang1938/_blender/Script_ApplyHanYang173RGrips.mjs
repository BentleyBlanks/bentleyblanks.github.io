import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
export async function ApplyHanYang173RGrips(reportPath,capturePath) {
 const fits=JSON.parse(await fs.readFile(reportPath,'utf8'));
 const capture=JSON.parse(await fs.readFile(capturePath,'utf8'));
 const grips={};
 for(const [key,f] of Object.entries(fits))grips[key]=Object.fromEntries(['position','rotation','fingerRotations'].map(k=>[k,f[k]]));
 const Mul=([x,y,z,w],[X,Y,Z,W])=>[w*X+x*W+y*Z-z*Y,w*Y-x*Z+y*W+z*X,w*Z+x*Y-y*X+z*W,w*W-x*X-y*Y-z*Z];
 const r=grips.hip_r;r.triggerRotations=Object.fromEntries(['1','11','12'].map(k=>[k,r.fingerRotations[k].slice()]));
 for(const key of ['11','12']){
  const c=Object.entries(capture.chain.r).find(([name])=>name.toLowerCase().endsWith('finger'+key))[1],angle=key==='11'?.02:.01;
  r.triggerRotations[key]=Mul(r.triggerRotations[key],[...c.axis.map(v=>v*Math.sin(angle/2)),Math.cos(angle/2)]);
 }
 const source='// Production skin fitted against Dots 173R; generated by Script_ApplyHanYang173RGrips.mjs.\nconst grips='+JSON.stringify(grips,null,2)+';\n'+
  'export function HanYang173RPose(base) {\n  const right=Object.freeze({...base.right,...grips.hip_r}),left=Object.freeze({...base.left,...grips.hip_l});\n  return {...base,right,left,adsSupport:grips.ads_l};\n}\n';
 await fs.writeFile(path.join(path.dirname(fileURLToPath(import.meta.url)),'../Data_HanYang173RGrips.mjs'),source);
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))await ApplyHanYang173RGrips(process.argv[2],process.argv[3]);
