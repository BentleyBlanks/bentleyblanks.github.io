"""Calibrate the immutable Dots PBR inputs for the game's existing forward pass.
Only writes calibration metadata/data. It never changes geometry or image bytes.
Python dependencies: numpy, Pillow. Run from the repository root.
"""
import json,struct,hashlib
from pathlib import Path
from io import BytesIO
import numpy as np
from PIL import Image
root=Path(__file__).resolve().parent.parent
b=(root/'Model/HanYang173R/Model_HanYang173R.glb').read_bytes();n=struct.unpack_from('<I',b,12)[0]
d=json.loads(b[20:20+n]);binary=b[28+n:]
def Read(i):
    a=d['accessors'][i];v=d['bufferViews'][a['bufferView']];w={'SCALAR':1,'VEC2':2,'VEC3':3,'VEC4':4}[a['type']]
    typ={5126:'<f4',5125:'<u4',5123:'<u2'}[a['componentType']];size=np.dtype(typ).itemsize
    return np.ndarray((a['count'],w),dtype=typ,buffer=binary,offset=v.get('byteOffset',0)+a.get('byteOffset',0),strides=(v.get('byteStride',w*size),size)).copy()
def Linear(c):return np.where(c<=.04045,c/12.92,((c+.055)/1.055)**2.4)
gains={};rows=[]
for node in d['nodes']:
    name=node.get('name','')
    if 'mesh' not in node or ('Wood' in name and name!='SideWoodButton'):continue
    p=d['meshes'][node['mesh']]['primitives'][0];pbr=d['materials'][p['material']]['pbrMetallicRoughness']
    uv=Read(p['attributes']['TEXCOORD_0'])[Read(p['indices']).reshape((-1,3))].mean(axis=1)
    image=d['images'][d['textures'][pbr['baseColorTexture']['index']]['source']];v=d['bufferViews'][image['bufferView']]
    raw=binary[v.get('byteOffset',0):v.get('byteOffset',0)+v['byteLength']];a=np.array(Image.open(BytesIO(raw)).convert('RGB'));h,w=a.shape[:2]
    samples=a[np.clip((uv[:,1]*h).astype(int),0,h-1),np.clip((uv[:,0]*w).astype(int),0,w-1)]
    median=np.median(samples,axis=0);luma=float(Linear(median/255) @ [.2126,.7152,.0722])
    # Dark sight blades/interior lips retain their distinct finish. Other
    # exposed metal uses a display-calibrated conductor response, not a claim
    # about the historical rifle's measured optical constants.
    dark=name.startswith(('Sight_','HY150_','HY151_','HY153_','HY155_'))
    target=.45 if name.startswith('Handle') else .50
    gain=2.5 if dark else target/max(luma,.001)
    gains[name]=round(gain,3)
    rows.append({'part':name,'sourceBaseMedianSrgb':median.tolist(),'sourceMedianLinearLuma':luma,'gain':gains[name],'darkFinish':dark,'targetLinearLuma':None if dark else target})
record={'version':'Cod14Metal20261025','gameSha256':hashlib.sha256(b).hexdigest(),'method':'Unweighted triangle-UV-centroid samples of immutable source BaseColor; sRGB decoded before luma. Artistic reflectance normalization; effective RGB is capped at 0.95 after texture multiplication. Source images and geometry unchanged.','roughnessGain':1.4,'maximumReflectance':.95,'parts':rows,
 'references':['https://www.imfdb.org/index.php?title=File:CODWWII_Kar98K_(1).jpg','https://www.imfdb.org/index.php?title=File:CoDWWII-k98k_2.jpg']}
(root/'Model/HanYang173R/Data_MaterialCalibration.json').write_text(json.dumps(record,indent=2)+'\n',encoding='utf8')
(root/'Data_HanYang173RMaterials.mjs').write_text('// Generated by _import/Script_HanYang173RMaterials.py; runtime PBR calibration only.\nexport const HANYANG_METAL_GAINS = Object.freeze('+json.dumps(gains,indent=2)+');\n',encoding='utf8')
print('Calibrated',len(gains),'metal parts; source images/geometry preserved')
