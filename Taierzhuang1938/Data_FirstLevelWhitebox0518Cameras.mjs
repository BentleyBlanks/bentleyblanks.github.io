// 第一关 05–18 白盒对照机位（docs/Data_FirstLevelWhitebox0518Gap.md）。
// 每一张 Notion「第一关｜游戏概念参考图」对应一个游戏内机位，出图脚本
// Script_FirstLevelWhitebox0518Shots.mjs 照这张表拍现状，供和概念图逐张对比。
//
// 约定（与 Script_EditorSamplePoints.ApplyPose 一致）：
//   · camera.x / camera.z 世界米；camera.y 省略时取「共享地面 + h」，h 默认 1.6（站姿眼高）。
//   · yawDeg：0 = 朝北（-Z），+90 = 朝西（-X），-90 = 朝东，180 = 朝南。由 look 点算出，
//     look 是这一张图「看向哪儿」的世界坐标，改机位时改 look，不要手改 yawDeg。
//   · pitchDeg：负数低头。fov 默认 55（游戏竖直 FOV）。
//   · stage：missionStage=N 进哪一阶段（人物、战车、门的状态按该阶段的起步现场）。
//   · scenario：可选，拍前切到的 layout.scenario 态（只有 18_2 夜门用 NightGate；只换几何，不换夜间光照）。
// 机位取自 MISSION_ANCHORS / MISSION_ROUTES / MISSION_PLACEMENT / FRONT_SORTIE 的点（见每条 note），
// 不是概念图里的精确透视 —— 概念图的距离感不直接当米制。纯数据，无 three 依赖。
const Yaw = (camera, look) => Math.atan2(-(look.x - camera.x), -(look.z - camera.z)) * 180 / Math.PI;
function Shot(id, stage, camera, look, extra = {}) {
  return Object.freeze({
    id, stage, camera: Object.freeze({ h: 1.6, ...camera }), look: Object.freeze(look),
    yawDeg: +Yaw(camera, look).toFixed(2), pitchDeg: -3, fov: 55, ...extra,
  });
}
