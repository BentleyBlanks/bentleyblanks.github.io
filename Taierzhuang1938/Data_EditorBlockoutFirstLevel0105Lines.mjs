//            subtitle: 屏幕字幕（中文）, direction: 表演提示（先身体后情绪）, projection: shout|normal|low|breath（音量档，
//            提示词用词 + 整段母带电平）, kanji?: 日语稿面, vocal?: true = 非词人声（嚎、痛叫），时间戳对不上字不算漏句 }

const L = (who, speaker, lang, text, subtitle, direction, projection = "normal", extra = {}) =>
  Object.freeze({ who, speaker, lang, text, subtitle, direction, projection, ...extra });
const JA = (who, speaker, kana, kanji, subtitle, direction, projection = "normal") =>
  L(who, speaker, "ja", kana, subtitle, direction, projection, { kanji });

function Scene(id, beat, label, context, lines) {
  const numbered = lines.map((line, i) => Object.freeze({ id: `${id}.${String(i + 1).padStart(2, "0")}`, ...line }));
  return Object.freeze({ id, beat, label, context, cast: Object.freeze([...new Set(lines.map((l) => l.who))]), lines: Object.freeze(numbered) });
}

